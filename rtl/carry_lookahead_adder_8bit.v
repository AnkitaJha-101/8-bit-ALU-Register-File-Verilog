// ============================================================================
// Module Name: carry_lookahead_adder_8bit
// Description: Hierarchical 8-bit Carry Look-Ahead Adder (CLA) composed of two
//              4-bit CLA blocks with block-level lookahead carry logic.
// Standard:    Verilog-2001 (Synthesizable)
// Author:      Senior RTL Design Engineer
// Project:     8-bit ALU with Register File & Adder Architecture Analysis
// ============================================================================

`timescale 1ns / 1ps

module carry_lookahead_adder_8bit (
    input  wire [7:0] a,
    input  wire [7:0] b,
    input  wire       cin,
    output wire [7:0] sum,
    output wire       cout
);

    wire c4;            // Carry from lower 4-bit block to upper 4-bit block
    wire p_blk0, g_blk0; // Block propagate/generate for bits [3:0]
    wire p_blk1, g_blk1; // Block propagate/generate for bits [7:4]

    // Lower 4-bit CLA block
    cla_4bit cla_low (
        .a    (a[3:0]),
        .b    (b[3:0]),
        .cin  (cin),
        .sum  (sum[3:0]),
        .cout (), // Intermediate cout generated by block lookahead logic
        .p_blk(p_blk0),
        .g_blk(g_blk0)
    );

    // Block-level Lookahead Carry Generation for bit 4
    // c4 = G0 + (P0 & cin)
    assign c4 = g_blk0 | (p_blk0 & cin);

    // Upper 4-bit CLA block
    cla_4bit cla_high (
        .a    (a[7:4]),
        .b    (b[7:4]),
        .cin  (c4),
        .sum  (sum[7:4]),
        .cout (),
        .p_blk(p_blk1),
        .g_blk(g_blk1)
    );

    // Final Carry Out lookahead calculation
    // cout = G1 + (P1 & c4) = G1 + (P1 & G0) + (P1 & P0 & cin)
    assign cout = g_blk1 | (p_blk1 & c4);

endmodule
